export type StringKey = keyof typeof STRINGS.it;

@Injectable({ providedIn: 'root' })
export class I18nService {
  private readonly _lang = signal<Lang>(
    (() => {
      try {
        return (localStorage.getItem('lang') as Lang | null) ?? 'it';
      } catch {
        return 'it';
      }
    })(),
  );

  readonly lang = this._lang.asReadonly();

  t(key: StringKey): string {
    return STRINGS[this._lang()][key];
  }

  /** Like t(), replacing {name} placeholders with the given values. */
  tp(key: StringKey, params: Record<string, string | number>): string {
    return this.t(key).replace(/\{(\w+)\}/g, (m, k: string) => (k in params ? String(params[k]) : m));
  }

  toggle(): void {
    const next: Lang = this._lang() === 'it' ? 'en' : 'it';
    try {
      localStorage.setItem('lang', next);
    } catch {
      // private browsing — ignore
    }
    this._lang.set(next);
  }
}
